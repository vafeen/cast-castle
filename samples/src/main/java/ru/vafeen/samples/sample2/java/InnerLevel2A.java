package ru.vafeen.samples.sample2.java;

class InnerLevel2A {
    private final String x;
    private final int y;

    public InnerLevel2A(String x, int y) {
        this.x = x;
        this.y = y;
    }

    public String getX() {
        return x;
    }

    public int getY() {
        return y;
    }
}