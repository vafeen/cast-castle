package ru.vafeen.samples.sample2.java;

class InnerLevel2B {
    private final int x;
    private final String y;

    public InnerLevel2B(int x, String y) {
        this.x = x;
        this.y = y;
    }

    public int getX() {
        return x;
    }

    public String getY() {
        return y;
    }
}