package ru.vafeen.samples.sample1.java;
public class InnerLevel3A {
    private final int first;
    private final String second;

    public InnerLevel3A(int first, String second) {
        this.first = first;
        this.second = second;
    }

    public int getFirst() {
        return first;
    }

    public String getSecond() {
        return second;
    }
}